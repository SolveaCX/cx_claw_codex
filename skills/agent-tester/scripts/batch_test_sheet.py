#!/usr/bin/env python3
"""Create and submit system-compatible Agent Tester batch-test workbooks.

Input JSON is a list of cases.  Chatflow cases accept ``turns`` with ``question``
and optional ``metadata``; ordinary Agent cases accept one ``question``.
"""

import os
import sys
sys.path.insert(0, os.path.join(os.environ.get("SOLVEA_LIB_DIR", os.path.join(os.path.dirname(__file__), "..", "..", "__lib__")), "skill-runtime"))
from bootstrap import *  # noqa: F401,F403

import argparse
import json
from pathlib import Path

from openpyxl import Workbook
from openpyxl.styles import Alignment, Font, PatternFill
from openpyxl.utils import get_column_letter

from client import SolveaClient


CHATFLOW_HEADERS = ["case_name", "chat_id"]
REPLY_HEADERS = [
    "question", "origin_answer", "ai_answer", "similarity", "judgement",
    "reason", "chat_id", "meta_data", "fail_reason",
]

REPLY_INSTRUCTION = (
    "Do not delete this row. Fill question and optional meta_data; all result columns are generated by the system. "
    "REPLY meta_data must use plain text key: value pairs separated by semicolons, for example "
    "touchPoint: LIVE_CHAT; order_number: A-1001."
)


def _metadata_text(value):
    if value in (None, ""):
        return ""
    if isinstance(value, str):
        return value
    if not isinstance(value, dict):
        raise ValueError("turn metadata must be an object or a string")
    return json.dumps(value, ensure_ascii=False, separators=(",", ":"))


def _reply_metadata_text(value):
    """Render metadata in the key/value syntax consumed by the REPLY backend."""
    if value in (None, ""):
        return ""
    if isinstance(value, dict):
        return "; ".join(f"{key}: {val}" for key, val in value.items())
    if isinstance(value, str):
        stripped = value.strip()
        if stripped.startswith("{") and stripped.endswith("}"):
            try:
                parsed = json.loads(stripped)
            except json.JSONDecodeError:
                parsed = None
            if isinstance(parsed, dict):
                return _reply_metadata_text(parsed)
        return value
    raise ValueError("REPLY metadata must be an object or a string")


def _load_cases(path):
    cases = json.loads(Path(path).read_text(encoding="utf-8"))
    if not isinstance(cases, list) or not cases:
        raise ValueError("cases JSON must be a non-empty array")
    return cases


def build_workbook(cases, mode):
    if mode not in {"chatflow", "agent"}:
        raise ValueError("mode must be chatflow or agent")
    if len(cases) > (600 if mode == "chatflow" else 200):
        raise ValueError(f"{mode} batch testing supports at most {600 if mode == 'chatflow' else 200} cases")

    workbook = Workbook()
    sheet = workbook.active
    sheet.title = "Batch Test"
    instruction = sheet.cell(row=1, column=1)
    instruction.alignment = Alignment(wrap_text=True, vertical="top")
    instruction.font = Font(italic=True, color="666666")

    if mode == "chatflow":
        normalized = []
        max_turns = 0
        for index, case in enumerate(cases, start=1):
            turns = case.get("turns") if isinstance(case, dict) else None
            if not isinstance(turns, list) or not turns:
                raise ValueError(f"case {index} requires a non-empty turns array")
            normalized_turns = []
            for turn in turns:
                question = turn.get("question", turn.get("message", "")) if isinstance(turn, dict) else ""
                if not isinstance(question, str) or not question.strip():
                    raise ValueError(f"case {index} contains an empty question")
                normalized_turns.append((turn.get("metadata") if isinstance(turn, dict) else None, question.strip()))
            max_turns = max(max_turns, len(normalized_turns))
            normalized.append((str(case.get("case_name") or f"case_{index}"), normalized_turns))

        headers = list(CHATFLOW_HEADERS)
        for turn_number in range(1, max_turns + 1):
            headers.extend([f"metadata_{turn_number}", f"question_{turn_number}", f"ai_answer_{turn_number}"])
        instruction.value = (
            "Do not delete this row. One row is one multi-turn case. Fill case_name, metadata_N and question_N; "
            "chat_id and ai_answer_N are generated by the system."
        )
        sheet.append(headers)
        for case_name, turns in normalized:
            row = [case_name, ""]
            for metadata, question in turns:
                row.extend([_metadata_text(metadata), question, ""])
            row.extend([""] * (len(headers) - len(row)))
            sheet.append(row)
    else:
        instruction.value = REPLY_INSTRUCTION
        sheet.append(REPLY_HEADERS)
        for index, case in enumerate(cases, start=1):
            if not isinstance(case, dict):
                raise ValueError(f"case {index} must be an object")
            question = case.get("question", case.get("message", ""))
            if not isinstance(question, str) or not question.strip():
                raise ValueError(f"case {index} requires question")
            sheet.append([
                question.strip(), "", "", "", "", "", "",
                _reply_metadata_text(case.get("metadata")), "",
            ])

    for cell in sheet[2]:
        cell.font = Font(bold=True, color="FFFFFF")
        cell.fill = PatternFill("solid", fgColor="1E3A5F")
        cell.alignment = Alignment(horizontal="center", vertical="center", wrap_text=True)
    sheet.freeze_panes = "A3"
    sheet.row_dimensions[1].height = 48
    for column in range(1, sheet.max_column + 1):
        sheet.column_dimensions[get_column_letter(column)].width = 22
    return workbook


def _write_state(data):
    state_path = STATE_DIR / "latest_batch_test.json"
    state_path.parent.mkdir(parents=True, exist_ok=True)
    state_path.write_text(json.dumps(data, ensure_ascii=False, indent=2), encoding="utf-8")


def create_sheet(args):
    cases = _load_cases(args.cases_file)
    output = Path(args.output) if args.output else OUTPUTS_DIR / f"{args.mode}_batch_test_{timestamp()}.xlsx"
    output.parent.mkdir(parents=True, exist_ok=True)
    build_workbook(cases, args.mode).save(output)
    result = {"mode": args.mode, "case_count": len(cases), "file": str(output)}
    _write_state({"stage": "sheet_created", **result})
    return result


def submit(args):
    if args.flow_version is not None and args.agent_id is None:
        raise ValueError("--flow-version requires --agent-id")
    if args.agent_id is not None and args.flow_version is None:
        raise ValueError("--agent-id requires --flow-version")
    client = SolveaClient(env=args.env, project_id=args.project_id)
    file_key = client.upload_batch_test_file(args.file)
    task_type = "MULTI_TURN_REPLY" if args.mode == "chatflow" else "REPLY"
    metadata = None
    if args.agent_id is not None:
        metadata = {"specified_agent_id": args.agent_id, "specified_flow_version": args.flow_version}
    result = client.submit_batch_test(file_key, task_type, bot_id=args.bot_id or client.bot_id, metadata=metadata)
    state = {
        "stage": "submitted", "mode": args.mode, "file": str(Path(args.file).resolve()),
        "file_key": file_key, "task_type": task_type, "agent_id": args.agent_id,
        "flow_version": args.flow_version, "submission_result": result,
    }
    _write_state(state)
    return state


def get_tasks(args):
    client = SolveaClient(env=args.env, project_id=args.project_id)
    task_type = "MULTI_TURN_REPLY" if args.mode == "chatflow" else "REPLY"
    return client.get_label_tasks(page=args.page, page_size=args.page_size, task_type=task_type)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("command", choices=["create-sheet", "submit", "get-tasks"])
    parser.add_argument("--mode", choices=["chatflow", "agent"], required=True)
    parser.add_argument("--cases-file")
    parser.add_argument("--output")
    parser.add_argument("--file")
    parser.add_argument("--agent-id", type=int)
    parser.add_argument("--flow-version", type=int)
    parser.add_argument("--bot-id", type=int)
    parser.add_argument("--project-id")
    parser.add_argument("--env", choices=["staging", "prod"], default=SOLVEA_ENV)
    parser.add_argument("--page", type=int, default=1)
    parser.add_argument("--page-size", type=int, default=20)
    args = parser.parse_args()
    if args.command == "create-sheet":
        if not args.cases_file:
            parser.error("create-sheet requires --cases-file")
        result = create_sheet(args)
    elif args.command == "submit":
        if not args.file:
            parser.error("submit requires --file")
        result = submit(args)
    else:
        result = get_tasks(args)
    print(json.dumps(result, ensure_ascii=False, indent=2))


if __name__ == "__main__":
    main()
