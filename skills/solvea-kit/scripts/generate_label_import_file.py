#!/usr/bin/env python3
"""Generate label-tree import xlsx from structured JSON.

This is a solvea-kit workflow helper, not a backend API wrapper. The generated
xlsx is meant to be passed to:

    npx --yes @shulex/cxclawctl@latest api upload-labels --tree-id <id> --file <xlsx>
"""

import os
import sys
sys.path.insert(0, os.path.join(
    os.environ.get("SOLVEA_LIB_DIR", os.path.join(os.path.dirname(__file__), "..", "..", "__lib__")),
    "skill-runtime",
))
from bootstrap import STATE_DIR  # noqa: E402

import argparse
import json
from pathlib import Path

from openpyxl import Workbook
from openpyxl.styles import Alignment, Font, PatternFill
from openpyxl.utils import get_column_letter


INIT_NOTICE = (
    "The information of this row cannot be deleted! Tips:\n"
    "1. first_level is the first level that is not empty.\n"
    "2. second_level is the second level.\n"
    "3. third_level is the third level.\n"
    "4. fourth_level is the fourth level.\n"
    "5. \"Name\", \"describe\" and \"example\" are for the use of the large model. Do not repeat them."
)

UPDATE_NOTICE = (
    "The information of this row cannot be deleted! Tips:\n"
    "1. The \"id\" is automatically generated by the program. When it is empty, it indicates adding a new tag. When it is an existing ID, it represents updating the current tag information.\n"
    "2. \"Name\", \"describe\" and \"example\" are for the use of the large model. Do not repeat them.\n"
    "3. Fill in the \"parent_ID\" with the ID of the parent node tag.\n"
    "4.If \"is_Tag\" is 1, it represents tagging as a tag. If it is 0, it will not be tagged to the work order."
)


def _load_labels(path: Path) -> list[dict]:
    data = json.loads(path.read_text(encoding="utf-8"))
    labels = data.get("labels") if isinstance(data, dict) else data
    if not isinstance(labels, list) or not labels:
        raise ValueError("input requires a non-empty labels array")
    for label in labels:
        if not isinstance(label, dict):
            raise ValueError("each label must be a JSON object")
    return labels


def _examples(label: dict) -> list[str]:
    examples = label.get("examples") or label.get("exampleList") or []
    if not isinstance(examples, list):
        raise ValueError("examples must be an array")
    return [str(value).strip() for value in examples[:5]] + [""] * max(0, 5 - len(examples))


def _init_rows(labels: list[dict]) -> list[list]:
    rows = [
        [INIT_NOTICE],
        ["first_level", "second_level", "third_level", "fourth_level",
         "describe", "example1", "example2", "example3", "example4", "example5"],
    ]
    for label in labels:
        path = label.get("path") or [
            label.get("firstLevel") or label.get("first_level") or "",
            label.get("secondLevel") or label.get("second_level") or "",
            label.get("thirdLevel") or label.get("third_level") or "",
            label.get("fourthLevel") or label.get("fourth_level") or "",
        ]
        if not isinstance(path, list) or not path or not str(path[0]).strip():
            raise ValueError("init labels require path or first_level/firstLevel")
        path = [str(value).strip() for value in path[:4]] + [""] * max(0, 4 - len(path))
        rows.append(path[:4] + [label.get("describe", "")] + _examples(label)[:5])
    return rows


def _update_rows(labels: list[dict]) -> list[list]:
    rows = [
        [UPDATE_NOTICE],
        ["id", "name", "describe", "example1", "example2", "example3", "example4", "example5",
         "is_tag", "level", "parent_id", "path"],
    ]
    for label in labels:
        name = label.get("name") or label.get("nodeName")
        if not name:
            raise ValueError("update labels require name or nodeName")
        is_tag = label.get("isTag", label.get("is_tag", 1))
        if isinstance(is_tag, bool):
            is_tag = 1 if is_tag else 0
        rows.append([
            label.get("id", ""),
            name,
            label.get("describe", label.get("nodeDescribe", "")),
            *_examples(label)[:5],
            is_tag,
            label.get("level", ""),
            label.get("parentId", label.get("parent_id", 0)),
            label.get("path", ""),
        ])
    return rows


def write_workbook(labels: list[dict], output_path: Path, init: bool = False) -> dict:
    rows = _init_rows(labels) if init else _update_rows(labels)
    output_path.parent.mkdir(parents=True, exist_ok=True)

    wb = Workbook()
    ws = wb.active
    ws.title = "labels"
    for row in rows:
        ws.append(row)

    ws["A1"].font = Font(bold=True, color="9C6500")
    ws["A1"].fill = PatternFill("solid", fgColor="FFF2CC")
    ws["A1"].alignment = Alignment(wrap_text=True, vertical="top")
    ws.row_dimensions[1].height = 78
    for cell in ws[2]:
        cell.font = Font(bold=True)
        cell.fill = PatternFill("solid", fgColor="D9EAF7")
    for column in range(1, ws.max_column + 1):
        ws.column_dimensions[get_column_letter(column)].width = 18

    wb.save(output_path)
    return {
        "file": str(output_path),
        "format": "init" if init else "update",
        "rows": len(labels),
    }


def main() -> None:
    parser = argparse.ArgumentParser(description="Generate label-tree import xlsx from JSON")
    parser.add_argument("--input", "--data-file", dest="input", required=True, help="JSON file with labels array")
    parser.add_argument("--output", help="Output xlsx path")
    parser.add_argument("--init", action="store_true", help="Generate initialization format for empty trees")
    parser.add_argument("--pretty", action="store_true", help="Pretty print JSON result")
    args = parser.parse_args()

    output_path = Path(args.output) if args.output else STATE_DIR / ("labels_init.xlsx" if args.init else "labels_update.xlsx")
    result = write_workbook(_load_labels(Path(args.input)), output_path, init=args.init)
    print(json.dumps(result, indent=2 if args.pretty else None, ensure_ascii=False))


if __name__ == "__main__":
    main()
