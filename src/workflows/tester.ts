import { join } from "node:path";
import ExcelJS from "exceljs";
import type { Session } from "../types.js";
import { option } from "../args.js";
import { SolveaClient } from "../solvea/client.js";
import {
  asRows,
  ensureParent,
  intOption,
  outputRoot,
  readJson,
  stateRoot,
  writeJson,
} from "./common.js";

type JsonObject = Record<string, unknown>;

export const CHATFLOW_HEADERS = ["case_name", "chat_id"];
export const REPLY_HEADERS = [
  "question",
  "origin_answer",
  "ai_answer",
  "similarity",
  "judgement",
  "reason",
  "chat_id",
  "meta_data",
  "fail_reason",
];

const REPLY_INSTRUCTION =
  "Do not delete this row. Fill question and optional meta_data; all result columns are generated by the system. REPLY meta_data must use plain text key: value pairs separated by semicolons, for example touchPoint: LIVE_CHAT; order_number: A-1001.";

function mode(args: string[]) {
  const value = option(args, "--mode", true);
  if (value !== "chatflow" && value !== "agent")
    throw new Error("--mode must be chatflow or agent");
  return value;
}

export function batchTaskType(value: "chatflow" | "agent") {
  return value === "chatflow" ? "MULTI_TURN_REPLY" : "REPLY";
}

function metadataText(value: unknown) {
  if (value === undefined || value === null || value === "") return "";
  if (typeof value === "string") return value;
  if (!value || typeof value !== "object" || Array.isArray(value))
    throw new Error("turn metadata must be an object or a string");
  return JSON.stringify(value);
}

function replyMetadataText(value: unknown) {
  if (value === undefined || value === null || value === "") return "";
  if (typeof value === "object" && !Array.isArray(value))
    return Object.entries(value as Record<string, unknown>)
      .map(([key, item]) => `${key}: ${String(item)}`)
      .join("; ");
  if (typeof value !== "string") throw new Error("REPLY metadata must be an object or a string");
  const trimmed = value.trim();
  if (trimmed.startsWith("{") && trimmed.endsWith("}")) {
    try {
      const parsed = JSON.parse(trimmed);
      if (parsed && typeof parsed === "object" && !Array.isArray(parsed))
        return replyMetadataText(parsed);
    } catch {
      // Preserve non-JSON text for the backend to validate.
    }
  }
  return value;
}

async function casesFrom(file: string) {
  if (file.endsWith(".json")) return asRows(await readJson(file));
  const workbook = new ExcelJS.Workbook();
  await workbook.xlsx.readFile(file);
  const sheet = workbook.worksheets[0];
  if (!sheet) throw new Error("cases workbook has no worksheet");
  const headers = (sheet.getRow(1).values as unknown[]).slice(1).map((v) => String(v ?? ""));
  const rows: JsonObject[] = [];
  sheet.eachRow((row, number) => {
    if (number === 1) return;
    const values = (row.values as unknown[]).slice(1),
      item: JsonObject = {};
    headers.forEach((header, index) => {
      if (header) item[header] = values[index] ?? "";
    });
    rows.push(item);
  });
  return rows;
}

export async function buildWorkbook(cases: JsonObject[], selectedMode: "chatflow" | "agent") {
  const limit = selectedMode === "chatflow" ? 600 : 200;
  if (cases.length > limit)
    throw new Error(`${selectedMode} batch testing supports at most ${limit} cases`);

  const workbook = new ExcelJS.Workbook();
  const sheet = workbook.addWorksheet("Batch Test");
  const instruction =
    selectedMode === "chatflow"
      ? "Do not delete this row. One row is one multi-turn case. Fill case_name, metadata_N and question_N; chat_id and ai_answer_N are generated by the system."
      : REPLY_INSTRUCTION;
  sheet.addRow([instruction]);

  if (selectedMode === "chatflow") {
    const normalized = cases.map((item, index) => {
      const turns = Array.isArray(item.turns)
        ? item.turns
        : item.question || item.message
          ? [{ question: item.question ?? item.message, metadata: item.metadata }]
          : [];
      if (!turns.length) throw new Error(`case ${index + 1} requires a non-empty turns array`);
      return {
        name: String(item.case_name ?? `case_${index + 1}`),
        turns: turns.map((turn) => {
          if (!turn || typeof turn !== "object")
            throw new Error(`case ${index + 1} contains an invalid turn`);
          const value = turn as JsonObject;
          const question = String(value.question ?? value.message ?? "").trim();
          if (!question) throw new Error(`case ${index + 1} contains an empty question`);
          return { question, metadata: metadataText(value.metadata) };
        }),
      };
    });
    const maxTurns = Math.max(1, ...normalized.map((item) => item.turns.length));
    const headers = [...CHATFLOW_HEADERS];
    for (let index = 1; index <= maxTurns; index += 1)
      headers.push(`metadata_${index}`, `question_${index}`, `ai_answer_${index}`);
    sheet.addRow(headers);
    for (const item of normalized) {
      const row: unknown[] = [item.name, ""];
      for (const turn of item.turns) row.push(turn.metadata, turn.question, "");
      while (row.length < headers.length) row.push("");
      sheet.addRow(row);
    }
  } else {
    sheet.addRow(REPLY_HEADERS);
    for (const [index, item] of cases.entries()) {
      const question = String(item.question ?? item.message ?? "").trim();
      if (!question) throw new Error(`case ${index + 1} requires question`);
      sheet.addRow([question, "", "", "", "", "", "", replyMetadataText(item.metadata), ""]);
    }
  }
  return workbook;
}

async function createSheet(args: string[]) {
  const selectedMode = mode(args);
  const cases = option(args, "--cases-file") ? await casesFrom(option(args, "--cases-file")!) : [];
  if (!cases.length) throw new Error("cases file must contain at least one case");
  const output =
    option(args, "--output") ?? join(outputRoot("agent-tester"), `cases_${Date.now()}.xlsx`);
  await ensureParent(output);
  const workbook = await buildWorkbook(cases, selectedMode);
  await workbook.xlsx.writeFile(output);
  const result = { output, count: cases.length, mode: selectedMode };
  await writeJson(join(stateRoot("agent-tester"), "latest_batch_test.json"), {
    stage: "sheet_created",
    ...result,
  });
  return result;
}

async function submit(client: SolveaClient, args: string[]) {
  const selectedMode = mode(args);
  const agentId = option(args, "--agent-id");
  const flowVersion = option(args, "--flow-version");
  if (Boolean(agentId) !== Boolean(flowVersion))
    throw new Error("--agent-id and --flow-version must be provided together");

  const file = await client.uploadTempFile(option(args, "--file", true)!);
  const result = await client.rawCall(
    "POST",
    `/api_v2/gpt/label/project/${await client.projectId()}/uploadMessage`,
    {
      file,
      type: batchTaskType(selectedMode),
      ...(option(args, "--bot-id") ? { botId: Number(option(args, "--bot-id")) } : {}),
      ...(agentId
        ? {
            metadata: {
              specified_agent_id: Number(agentId),
              specified_flow_version: Number(flowVersion),
            },
          }
        : {}),
    },
  );
  const output = {
    fileKey: file,
    result,
    mode: selectedMode,
    taskType: batchTaskType(selectedMode),
  };
  await writeJson(join(stateRoot("agent-tester"), "latest_batch_test.json"), {
    stage: "submitted",
    file,
    ...output,
  });
  return output;
}

export async function runAgentTester(
  session: Session | undefined,
  action: string | undefined,
  args: string[],
) {
  if (!action) throw new Error("agent-tester action is required");
  if (action === "create-sheet") return createSheet(args);
  if (!session) throw new Error(`${action} requires an authenticated tenant`);
  const client = new SolveaClient(session);
  if (action === "submit") return submit(client, args);
  if (action === "get-tasks") {
    const selectedMode = mode(args);
    return client.rawCall(
      "POST",
      `/api_v2/gpt/label/project/${await client.projectId()}/getLabelTask`,
      {
        page: intOption(args, "--page", 1),
        pageSize: intOption(args, "--page-size", 20),
        taskType: batchTaskType(selectedMode),
      },
    );
  }
  throw new Error(`unknown agent-tester action: ${action}`);
}
